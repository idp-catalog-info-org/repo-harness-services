package io.harness.pms.plan.execution.data.service.expressions.functors;

import io.harness.annotations.dev.CodePulse;
import io.harness.annotations.dev.HarnessModuleComponent;
import io.harness.annotations.dev.HarnessTeam;
import io.harness.annotations.dev.OwnedBy;
import io.harness.annotations.dev.ProductModule;
import io.harness.expression.LateBindingValue;

import java.util.Map;

@CodePulse(module = ProductModule.CDS, unitCoverageRequired = true, components = {HarnessModuleComponent.CDS_PIPELINE})
@OwnedBy(HarnessTeam.PIPELINE)
public class SimpleContextMapExpressionFunctor implements LateBindingValue {
  private final Map<String, Object> contextMap;

  public SimpleContextMapExpressionFunctor(Map<String, Object> contextMap) {
    this.contextMap = contextMap;
  }

  @Override
  public Object bind() {
    return contextMap;
  }
}
