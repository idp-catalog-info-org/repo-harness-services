package io.harness.beans;

import static io.harness.annotations.dev.HarnessTeam.PIPELINE;

import io.harness.annotations.dev.OwnedBy;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import com.fasterxml.jackson.annotation.JsonInclude;
import java.util.List;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

/**
 * Represents relationships between nodes in a workflow graph.
 * Similar to EdgeListInternal but with simplified structure for visualization.
 */
@OwnedBy(PIPELINE)
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
@JsonIgnoreProperties(ignoreUnknown = true)
@JsonInclude(JsonInclude.Include.NON_NULL)
public class WorkflowGraphRelation {
  private String parentId;
  private List<String> prevIds;
  private List<String> nextIds;
  private List<String> children; // Child nodes (renamed from edges)
}
